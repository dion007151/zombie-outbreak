class Map:
    def __init__(self, game):
        self.game = game
        self.mini_map = mini_map
        self.world_map = {}
        self.get_map()

    def get_map(self):
        for j, row in enumerate(self.mini_map):
            for i, value in enumerate(row):
                if value:
                    self.world_map[(i, j)] = value

    def draw(self):
        # Draw 2D map for debugging (optional)
        for y, row in enumerate(self.mini_map):
            for x, value in enumerate(row):
                if value:
                    color = (100, 100, 100)
                    if value == 2:
                        color = (150, 100, 50)
                    elif value == 3:
                        color = (50, 200, 50)
                    pg.draw.rect(self.game.screen, color, (x*50, y*50, 50, 50))
